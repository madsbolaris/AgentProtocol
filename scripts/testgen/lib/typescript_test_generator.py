def _generate_enum_tests_typescript(enum_info) -> List[str]:
    """Generate tests for a single enum (TypeScript)."""
    lines = []
    lines.append(f"describe('{enum_info.name} Enum Tests', () => {{")
    lines.append("")

    # Deduplicate values
    seen_test_names = set()

    # Test each enum value
    for value in enum_info.values:
        test_name = f"{to_camel_case(value)}_value"

        # Skip if we've already generated this test
        if test_name in seen_test_names:
            continue
        seen_test_names.add(test_name)

        lines.append(f"  it('should serialize and deserialize {value} correctly', () => {{")
        lines.append(f"    // Arrange: Get enum value")
        lines.append(f"    const enumValue = {enum_info.name}.{to_pascal_case(value)};")
        lines.append("")
        lines.append("    // Act: Serialize to string")
        lines.append(f"    const serialized = enumValue.toString();")
        lines.append("")
        lines.append("    // Assert: Value serializes correctly")
        lines.append(f"    expect(serialized).toBeDefined();")
        lines.append(f"    expect(serialized.length).toBeGreaterThan(0);")
        lines.append("")
        lines.append("    // Act: Parse back")
        lines.append(f"    const parsed = {enum_info.name}[serialized as keyof typeof {enum_info.name}];")
        lines.append("")
        lines.append("    // Assert: Round-trip successful")
        lines.append(f"    expect(parsed).toBe(enumValue);")
        lines.append("  });")
        lines.append("")

    # Test all enum values are valid
    lines.append(f"  it('should have all valid enum values', () => {{")
    lines.append(f"    // Arrange: Get all enum values")
    lines.append(f"    const allValues = Object.values({enum_info.name});")
    lines.append("")
    lines.append("    // Assert: Each value can be serialized and deserialized")
    lines.append("    allValues.forEach(value => {")
    lines.append("      const serialized = value.toString();")
    lines.append("      expect(serialized).toBeDefined();")
    lines.append(f"      const parsed = {enum_info.name}[serialized as keyof typeof {enum_info.name}];")
    lines.append("      expect(parsed).toBe(value);")
    lines.append("    });")
    lines.append("  });")
    lines.append("")

    lines.append("});")
    lines.append("")

    return lines
