def generate_role_tests(roles: List[str]) -> str:
    """Generate test methods for each ChatRole."""
    tests = []

    for role in roles:
        # Map role to message type
        message_type = {
            "system": "SystemMessage",
            "developer": "DeveloperMessage",
            "user": "UserMessage",
            "agent": "AgentMessage",
            "tool": "ToolMessage",
            "channel": "ChannelMessage"
        }.get(role, "UserMessage")

        # SystemMessage and DeveloperMessage use Content (singular string), not Contents (collection)
        if role in ["system", "developer"]:
            content_property = f'Content = "Test {role} role"'
        # ChannelMessage uses EventContent, not TextContent
        elif role == "channel":
            content_property = '''Contents = new List<AIContent>
            {
                new EventContent
                {
                    Name = "test_event",
                    Timestamp = DateTime.UtcNow,
                    Value = "Test channel event value"
                }
            }'''
        # ToolMessage uses FunctionResultContent, not TextContent
        elif role == "tool":
            content_property = '''Contents = new List<AIContent>
            {
                new FunctionResultContent
                {
                    CallId = "call_001",
                    Name = "test_tool",
                    Result = "Test tool result",
                    Audience = "agent"
                }
            }'''
        # All other roles use Contents collection with TextContent
        else:
            content_property = f'''Contents = new List<AIContent>
            {{
                new TextContent {{ Text = "Test {role} role" }}
            }}'''

        test = f'''    [Fact]
    public async Task EchoBot_Handles{role.capitalize()}Role()
    {{
        // Arrange: Create {message_type} per TypeSpec
        var message = new {message_type}
        {{
            MessageId = "msg_{role}_001",
            {content_property}
        }};

        var xml = _serializer.Serialize(message);
        var content = new StringContent(xml, Encoding.UTF8, "application/xml");

        // Act
        var response = await _client.PostAsync("/api/messages", content);

        // Assert: Bot can process {role} messages
        response.StatusCode.Should().Be(HttpStatusCode.OK,
            "Bot should accept messages with role={role}");
    }}
'''
        tests.append(test)

    return "\n".join(tests)


